/// Build insights for every category that has a rule and a non-zero size.
pub fn recommendations(rolled: &[Accum]) -> Vec<Recommendation> {
    let mut out = Vec::new();
    for rule in RULES {
        let idx = match categories::index_of(rule.category) {
            Some(idx) => idx,
            None => continue,
        };
        let allocated = rolled[idx].allocated;
        if allocated == 0 {
            continue;
        }
        out.push(Recommendation {
            id: rule.id,
            title: rule.title,
            category_id: rule.category,
            allocated,
            risk: rule.risk,
            what_is_it: rule.what,
            recommendation: rule.rec,
            user_data: rule.user_data,
        });
    }
    out.sort_by_key(|rec| std::cmp::Reverse(rec.allocated));
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn rolled_with(entries: &[(&str, u64)]) -> Vec<Accum> {
        let mut rolled = vec![Accum::default(); categories::CATEGORIES.len()];
        for (id, bytes) in entries {
            let idx = categories::index_of(id).unwrap();
            rolled[idx].allocated = *bytes;
        }
        rolled
    }

    #[test]
    fn builds_sorted_insights() {
        let rolled = rolled_with(&[
            ("developer.xcode.derived_data", 100),
            ("developer.docker", 50),
            ("system.caches", 10),
        ]);
        let insights = recommendations(&rolled);
        assert_eq!(insights.len(), 3);
        assert_eq!(insights[0].title, "Xcode DerivedData");
        assert_eq!(insights[0].risk, Risk::Low);
        assert!(!insights[0].user_data);
        assert_eq!(insights[1].title, "Docker");
        assert_eq!(insights[1].risk, Risk::High);
        assert!(insights[1].user_data);
    }

    #[test]
    fn skips_zero_and_unknown_categories() {
        let rolled = rolled_with(&[("developer.other", 999)]);
        assert!(recommendations(&rolled).is_empty());
    }
}
