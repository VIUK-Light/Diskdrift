//! Storage insights: what a category is, how risky it is, and what the user
//! could review. DiskDrift never deletes anything.

use crate::core::categories;
use crate::core::fs::Accum;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Risk {
    Informational,
    Low,
    Medium,
    High,
    Unknown,
}

impl Risk {
    pub fn label(self) -> &'static str {
        match self {
            Risk::Informational => "informational",
            Risk::Low => "low",
            Risk::Medium => "medium",
            Risk::High => "high",
            Risk::Unknown => "unknown",
        }
    }
}

#[derive(Debug, Clone)]
pub struct Recommendation {
    pub id: &'static str,
    pub title: &'static str,
    pub category_id: &'static str,
    pub allocated: u64,
    pub risk: Risk,
    pub what_is_it: &'static str,
    pub recommendation: &'static str,
    pub user_data: bool,
}

