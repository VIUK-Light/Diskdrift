pub fn index_of(id: &str) -> Option<usize> {
    CATEGORIES.iter().position(|c| c.id == id)
}

pub fn def(id: &str) -> Option<&'static CategoryDef> {
    index_of(id).map(|i| &CATEGORIES[i])
}

pub fn def_by_index(idx: usize) -> &'static CategoryDef {
    &CATEGORIES[idx]
}

/// True when `idx` is `ancestor` or a descendant of `ancestor`.
pub fn is_descendant_or_self(mut idx: usize, ancestor: usize) -> bool {
    loop {
        if idx == ancestor {
            return true;
        }
        match CATEGORIES[idx].parent {
            Some(p) => match index_of(p) {
                Some(pi) => idx = pi,
                None => return false,
            },
            None => return false,
        }
    }
}

pub fn children_of(idx: usize) -> Vec<usize> {
    let id = CATEGORIES[idx].id;
    CATEGORIES
        .iter()
        .enumerate()
        .filter(|(_, c)| c.parent == Some(id))
        .map(|(i, _)| i)
        .collect()
}

pub fn depth_of(mut idx: usize) -> usize {
    let mut d = 0;
    while let Some(p) = CATEGORIES[idx].parent {
        match index_of(p) {
            Some(pi) => {
                idx = pi;
                d += 1;
            }
            None => break,
        }
    }
    d
}

/// A short label that is unique when shown in a flat list,
/// e.g. `Xcode / CoreSimulator`.
pub fn display_name(idx: usize) -> String {
    let def = &CATEGORIES[idx];
    match def.parent.and_then(def_by_id) {
        Some(parent) if depth_of(idx) >= 2 => format!("{} / {}", parent.name, def.name),
        _ => def.name.to_string(),
    }
}

fn def_by_id(id: &str) -> Option<&'static CategoryDef> {
    def(id)
}

/// Resolve a user-supplied name to a category. Used by `explain`.
pub fn resolve_token(token: &str) -> Option<usize> {
    let t = token.trim().to_lowercase();
    let t = t.trim_end_matches('.').to_string();
    if t.is_empty() {
        return None;
    }
    // Exact id, then last id component, then name, then aliases.
    if let Some(i) = index_of(&t) {
        return Some(i);
    }
    for (i, c) in CATEGORIES.iter().enumerate() {
        if c.id.rsplit('.').next() == Some(t.as_str()) {
            return Some(i);
        }
    }
    for (i, c) in CATEGORIES.iter().enumerate() {
        if c.name.to_lowercase() == t {
            return Some(i);
        }
    }
    for (i, c) in CATEGORIES.iter().enumerate() {
        if c.aliases.iter().any(|a| *a == t) {
            return Some(i);
        }
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tree_is_well_formed() {
        for (i, c) in CATEGORIES.iter().enumerate() {
            if let Some(p) = c.parent {
                assert!(index_of(p).is_some(), "unknown parent {p} for {}", c.id);
                assert!(index_of(p).unwrap() < i, "parent must be declared first");
            }
        }
    }

    #[test]
    fn descendants() {
        let xcode = index_of("developer.xcode").unwrap();
        let sim = index_of("developer.xcode.core_simulator").unwrap();
        let dev = index_of("developer").unwrap();
        assert!(is_descendant_or_self(sim, xcode));
        assert!(is_descendant_or_self(sim, dev));
        assert!(!is_descendant_or_self(xcode, sim));
        assert!(is_descendant_or_self(dev, dev));
    }

    #[test]
    fn token_resolution() {
        assert_eq!(resolve_token("xcode"), index_of("developer.xcode"));
        assert_eq!(resolve_token("Xcode"), index_of("developer.xcode"));
        assert_eq!(
            resolve_token("coresimulator"),
            index_of("developer.xcode.core_simulator")
        );
        assert_eq!(resolve_token("hugging face"), index_of("ai.huggingface"));
        assert_eq!(
            resolve_token("Application Support"),
            index_of("applications.app_support")
        );
        assert_eq!(resolve_token("nope"), None);
    }
}
