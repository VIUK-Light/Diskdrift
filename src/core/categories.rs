//! The category tree. Rules (see `classify.rs`) map paths to these categories.
//!
//! The tree is intentionally small and data-driven. Adding a category must not
//! require touching the scanner core.

#[derive(Debug, Clone, Copy)]
pub struct CategoryDef {
    pub id: &'static str,
    pub name: &'static str,
    pub parent: Option<&'static str>,
    pub purpose: Option<&'static str>,
    /// Extra names accepted by `diskdrift explain`.
    pub aliases: &'static [&'static str],
}

macro_rules! cat {
    ($id:literal, $name:literal, $parent:literal, $purpose:literal, [$($alias:literal),* $(,)?]) => {
        CategoryDef {
            id: $id,
            name: $name,
            parent: Some($parent),
            purpose: Some($purpose),
            aliases: &[$($alias),*],
        }
    };
}

